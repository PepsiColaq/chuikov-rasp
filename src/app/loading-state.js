// Флаг «данные ещё грузятся с сервера».
//
// Раньше это была переменная в main.js, и экран расписания читал её через
// мост. Мост передаёт значения один раз при старте, поэтому экран всегда
// видел исходное `true` — даже когда данные уже пришли.
//
// Теперь это отдельная маленькая ячейка: main.js её выставляет, экран
// читает через функцию и всегда видит актуальное значение.

let loading = true

/** true, пока с сервера не пришли реальные ДЗ и замены (для скелетонов). */
export function isInitialDataLoading() {
  return loading
}

export function setInitialDataLoading(value) {
  loading = !!value
}
