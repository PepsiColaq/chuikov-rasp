// Флаг «есть что перерисовать, но сейчас нельзя».
//
// Зачем отдельный модуль: решение «отложить обновление» принимается в одном
// месте (пересборка панели), а используется в другом (цикл фоновой отрисовки).
// Пока человек печатает в поле — перерисовывать нельзя: узел уничтожится,
// клавиатура закроется, прокрутка улетит наверх.
//
// Раньше флаг жил в main.js как обычная переменная. Теперь он здесь, чтобы
// экраны могли его выставить, не заглядывая внутрь точки входа.

let pending = false

/** Есть ли отложенная перерисовка. */
export function isPendingRedraw() {
  return pending
}

/** Запомнить, что данные изменились и экран нужно обновить позже. */
export function setPendingRedraw(value) {
  pending = !!value
}
