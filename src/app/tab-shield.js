// «Щит» на время переключения вкладки.
//
// Пока идёт анимация перехода (4 секунды), фоновые обновления не должны
// перерисовывать экран — иначе переход дёргается. Раньше переменная и
// проверка лежали в разных файлах и общались через мост; мост передаёт
// только функции, поэтому проверка всегда видела 0 и щит не работал.
//
// Теперь и переменная, и проверка рядом — в одном модуле.

let shieldUntil = 0

/** Идёт ли сейчас переход между вкладками (не перерисовывать экран). */
export function tabSwitchShieldActive() {
  return Date.now() < shieldUntil
}

/** Включить щит на время анимации перехода. */
export function armTabSwitchShield(ms = 4000) {
  shieldUntil = Date.now() + ms
}
